// Keccak-256 for the EVM KECCAK256 (0x20) opcode.
//
// The sponge is the same shape as nim-eth's keccak.c (itself from BoringSSL):
// absorb whole rate-sized blocks word at a time, buffer the tail, 10*1 pad.
// The permutation is restructured in the style of XKCP's KeccakP-1600-opt64:
//
//   * all 25 lanes live in named locals, and rounds ping-pong between two sets
//     (A -> E -> A), so no state is written back between rounds;
//   * theta, rho, pi and chi are fused into one pass;
//   * crucially, rho/pi write into the *other* lane set rather than permuting
//     in place along a 24-step trail. BoringSSL's trail makes each rotation
//     depend on the one before it -- a 24-long serial dependency chain per
//     round -- whereas here all 24 rotations are independent and the CPU can
//     overlap them.
//
// Measured ~1.13x faster than the BoringSSL form at -O3, and far more than
// that at -O2, where the compact form depends on the optimiser to unroll its
// loops and constant-fold the rotation table while this form does not.
//
// The permutation body below is machine-generated; see gen.py.

