void keccak256_xkcp(const uint8_t *in, size_t in_len, uint8_t *out) {
  uint64_t state[25];
  memset(state, 0, sizeof(state));
  uint8_t *state_bytes = (uint8_t *)state;

  while (in_len >= RATE_BYTES) {
    for (size_t i = 0; i < RATE_BYTES / 8; i++) {
      uint64_t v;
      memcpy(&v, in + 8 * i, 8);
      state[i] ^= v;
    }
    keccak_f_fast(state);
    in += RATE_BYTES;
    in_len -= RATE_BYTES;
  }
  for (size_t i = 0; i < in_len; i++) state_bytes[i] ^= in[i];
  state_bytes[in_len] ^= 0x01;
  state_bytes[RATE_BYTES - 1] ^= 0x80;
  keccak_f_fast(state);
  memcpy(out, state_bytes, 32);
}
